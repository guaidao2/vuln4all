    # ---------------------------------------------------------------- 应用

    def create_app(self, ctx):
        app = ctx.flask(__name__)

        @app.route("/", methods=["GET", "POST"])
        def index():
            raw = ""
            verdict = None
            elapsed = None
            too_long = False
            safe_note = None

            if request.method == "POST":
                raw = request.form.get("tags", "")

                if len(raw) > MAX_INPUT:
                    too_long = True
                else:
                    started = time.monotonic()
                    # ↓↓↓ 洞就在这里：一条灾难性回溯的正则，跑在用户输入上 ↓↓↓
                    matched = PATTERN.match(raw) is not None
                    # ↑↑↑ 正确做法：把正则改写成 `^\w+(?:\s\w+)*$`（见 SAFE_PATTERN），
                    #     再给输入设长度上限 ↑↑↑
                    elapsed = time.monotonic() - started
                    verdict = "格式合法" if matched else "格式不合法"

                    if elapsed > DELAY_THRESHOLD:
                        ctx.progress.mark(GOAL)

            return render_template(
                "index.html",
                raw=raw,
                verdict=verdict,
                elapsed=elapsed,
                too_long=too_long,
                max_input=MAX_INPUT,
                pattern=PATTERN.pattern,
                safe_pattern=SAFE_PATTERN.pattern,
                safe_note=safe_note,
            )

        return {"": app}

    # ---------------------------------------------------------------- 进度

    def check(self, ctx):
        return {GOAL: ctx.progress.achieved(GOAL)}
