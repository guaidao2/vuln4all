"""标签列表校验处的正则回溯 —— ReDoS。

业务场景是"给文章打标签"：填一串标签（空格分隔），服务端校验格式合法不合法。

校验用的正则长这样：

    ^(\\w+\\s?)*$

看起来挺正常。而它是一条**灾难性回溯**的正则 —— 提交一小段精心构造的输入，
这一次校验就会跑上几秒、几十秒。

这一题要学的是一件很反直觉的事：

    **"慢"可以来自输入和数据的大小无关的地方。**
    27 个字符的输入让服务端卡了 1.6 秒（实测），
    而同样的正则处理 10 万个字符的正常输入只要 0.0003 秒。

这不是"输入太大"的问题 —— 是**匹配失败时要把指数级的切法全试一遍**。
"""

import re
import time

from vuln4all import Vuln, render_template, request

#: 开发写的"标签格式校验"。
#:
#: ↓↓↓ 洞就在这一条正则里 ↓↓↓
#:
#: `(\\w+\\s?)*` 之所以灾难性：`\\w+` 本身可以匹配任意多个字符，
#: `\\s?` 也可以匹配空 —— 于是"一个长串"在**拆成几个 \\w+** 这件事上有
#: 指数多种切法。匹配**成功**时正则引擎第一次就试对了，
#: 匹配**失败**时它必须把每一种切法都试完才敢说"不匹配"。
#:
#: 输入的尾部放一个 `!`（`\\w` 和 `\\s` 都不匹配它），就强制它走完所有切法。
#: 每多两个字符，切法数量 ×4 —— 所以时间是**指数**长的。
PATTERN = re.compile(r"^(\w+\s?)*$")

#: 上面那条正则的**安全写法**：把"分隔符 + 一个词"绑成一组，
#: 消掉"一个长串可以切成几种组合"这个歧义。
SAFE_PATTERN = re.compile(r"^\w+(?:\s\w+)*$")

#: 靶场自己的安全上限：输入最多这么长。
#:
#: 这一条**不是修复**（真实的修复是改写正则或者设长度上限 ——
#: 巧的是这里做的正是"设长度上限"，所以它确实是修复的一部分），
#: 这里加上它的首要目的是：不封顶的话，40 个字符的输入就能让一次请求
#: 卡住几分钟，靶场没法用。28 字符已经足够让"指数增长"这个性质
#: 舒服地演示出来（26 字符约 1.6 秒、28 字符约 6 秒）。
MAX_INPUT = 28

#: 超过这么久就认为"有人触发了灾难性回溯"。
DELAY_THRESHOLD = 2.0

GOAL = "用一段很短的输入让这次校验超过 2 秒"


